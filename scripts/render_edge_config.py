#!/usr/bin/env python3
"""Render the status site's Caddy configuration from the cache policy.

GitHub Pages cannot set response headers. The status site therefore keeps one
declared policy in ``deploy/cache-policy.json`` and one generated edge config;
the browser check serves the same policy from a loopback origin. Until the
domain is served by Caddy, the live Pages origin still caps every response at
its own short cache.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import site_cache

OUTPUT = Path("deploy/Caddyfile")
CSP_FILE = Path("templates/csp.txt")


def render(root: Path) -> str:
    policy = site_cache.load(root)
    csp_path = Path(root) / CSP_FILE
    if not csp_path.is_file():
        raise site_cache.PolicyError(f"{CSP_FILE} is missing")
    csp = csp_path.read_text(encoding="utf-8").strip()
    if not csp or "\n" in csp:
        raise site_cache.PolicyError(f"{CSP_FILE} must contain one policy line")
    return f"""# Code generated by scripts/render_edge_config.py from deploy/cache-policy.json.
# DO NOT EDIT. Run `make edge` to regenerate; `make edge-check` proves this file.
#
# The status site is a static file tree. Caddy owns the response headers that
# GitHub Pages cannot send; the policy file owns the cache values.

status.ia.sbktechno.com {{
\troot * {{$SBK_STATUS_ROOT:/var/lib/sbk/status/current}}
\tencode zstd gzip

\theader {{
\t\tX-Content-Type-Options "nosniff"
\t\tReferrer-Policy "no-referrer"
\t\tX-Frame-Options "DENY"
\t\t-Server
\t\t-X-Powered-By
\t}}

\theader ?Content-Security-Policy "{csp}; frame-ancestors 'none'"

\t@https protocol https
\theader @https >Strict-Transport-Security "max-age=31536000; includeSubDomains"

\t# Every response revalidates by default. Content-hashed names are immutable
\t# for a year, and the heartbeat stays no-store so a cached document cannot
\t# claim a state the publisher did not just send.
\theader ?Cache-Control "{policy.html}"

\t@hashed path_regexp {policy.hashed_pattern.pattern}
\theader @hashed {{
\t\tCache-Control "{policy.hashed}"
\t\tmatch status 2xx 304
\t}}

\theader /status.json >Cache-Control "{policy.status}"

\tfile_server
}}
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write deploy/Caddyfile")
    mode.add_argument("--check", action="store_true", help="fail when it is stale")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        expected = render(root)
    except (site_cache.PolicyError, OSError) as exc:
        print(f"edge config: {exc}", file=sys.stderr)
        return 1
    path = root / OUTPUT
    if args.write:
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            temporary = path.with_name(path.name + ".tmp")
            temporary.write_text(expected, encoding="utf-8")
            temporary.replace(path)
        print("edge config written")
        return 0
    if not path.is_file():
        print(f"edge config: {OUTPUT} is missing; run make edge", file=sys.stderr)
        return 1
    if path.read_text(encoding="utf-8") != expected:
        print(f"edge config: {OUTPUT} is stale; run make edge", file=sys.stderr)
        return 1
    print("edge config valid")
    return 0


if __name__ == "__main__":
    sys.exit(main())
